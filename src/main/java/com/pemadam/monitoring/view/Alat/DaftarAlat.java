    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
       
         if (selectedId == -1) {
            javax.swing.JOptionPane.showMessageDialog(parent, "Pilih data dulu!");
            return;
        }

        int confirm = javax.swing.JOptionPane.showConfirmDialog(
            parent,
            "Yakin mau hapus data ini?",
            "Konfirmasi",
            javax.swing.JOptionPane.YES_NO_OPTION
        );

        if (confirm == javax.swing.JOptionPane.YES_OPTION) {

            
            boolean sukses = controller.deleteAlat(selectedId);

            if (sukses) {
                javax.swing.JOptionPane.showMessageDialog(parent, "Data berhasil dihapus!");
                loadData();   
                selectedId = -1;
            } else {
                javax.swing.JOptionPane.showMessageDialog(parent, "Gagal hapus data!");
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void tblAlatMousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblAlatMousePressed
        
        int row = tblAlat.rowAtPoint(evt.getPoint());

        if (row == -1) {
            tblAlat.clearSelection(); 
            selectedId = -1;         
        }
    }//GEN-LAST:event_tblAlatMousePressed

    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
        if (selectedId == -1) {
            javax.swing.JOptionPane.showMessageDialog(parent, "Pilih data dulu!");
            return;
        }
        AlatModel a = controller.getAlatById(selectedId);
        DetailAlat dialog = new DetailAlat(parent, true);

        dialog.setData(
            a.getIdAlat(),
            a.getKodeAlat(),
            a.getNamaAlat(),
            a.getJenisAlat(),
            a.getTglPembelian(),
            a.getIdLokasi()
        );

        dialog.setLocationRelativeTo(this);
        dialog.setVisible(true);

        loadData();
    }//GEN-LAST:event_btnEditActionPerformed


