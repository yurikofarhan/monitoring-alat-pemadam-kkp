    private void loadData() {

        DefaultTableModel model = (DefaultTableModel) tblAlat.getModel();
        model.setRowCount(0);

        AlatController controller = new AlatController();
        List<AlatModel> list = controller.getAllAlat();

        int no = 1;

        for (AlatModel a : list) {
            model.addRow(new Object[]{
        a.getIdAlat(),
                no++,              
        a.getKodeAlat(),
        a.getNamaAlat(),
        a.getJenisAlat(),  
        a.getTglPembelian(),
        a.getNamaLokasi()
            });
        }
    }
    
    
