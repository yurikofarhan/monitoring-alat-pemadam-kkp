    private void loadData() {

        DefaultTableModel model = (DefaultTableModel) tblLokasi.getModel();
        model.setRowCount(0);

        LokasiController controller = new LokasiController();
        List<LokasiModel> list = controller.getAll();

        int no = 1;

        for (LokasiModel a : list) {
            model.addRow(new Object[]{
                a.getIdLokasi(),
                no++,              
                a.getNamaLokasi(),
                a.getLantai(),
                a.getGedung(),
                "Detail"
            });
        }
    }
    
    
