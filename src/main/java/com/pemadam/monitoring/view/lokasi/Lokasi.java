    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
        // TODO add your handling code here:
        if (selectedId == -1) {
            javax.swing.JOptionPane.showMessageDialog(parent, "Pilih data dulu!");
            return;
        }
        LokasiModel a = controller.getLokasiById(selectedId);
        DetailLokasiAlatDialog dialog = new DetailLokasiAlatDialog(parent, true);

        dialog.setData(a);

        dialog.setLocationRelativeTo(this);
        dialog.setVisible(true);

        loadData(); 
    }//GEN-LAST:event_btnEditActionPerformed

    private void tblLokasiMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblLokasiMouseClicked
       
        int row = tblLokasi.getSelectedRow();

        if (row != -1) {
            selectedId = Integer.parseInt(tblLokasi.getValueAt(row, 0).toString());
        }
    }//GEN-LAST:event_tblLokasiMouseClicked

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
       
         if (selectedId == -1) {
            javax.swing.JOptionPane.showMessageDialog(parent, "Pilih data dulu!");
            return;
        }

        int confirm = javax.swing.JOptionPane.showConfirmDialog(
            parent,
            "Yakin mau hapus data ini?",
            "Konfirmasi",
            javax.swing.JOptionPane.YES_NO_OPTION
        );

        if (confirm == javax.swing.JOptionPane.YES_OPTION) {

            LokasiController controller = new LokasiController();
            boolean sukses = controller.deleteLokasi(selectedId);

            if (sukses) {
                javax.swing.JOptionPane.showMessageDialog(parent, "Data berhasil dihapus!");
                loadData();   
                selectedId = -1;
            } else {
                javax.swing.JOptionPane.showMessageDialog(parent, "Gagal hapus data!");
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void tblLokasiMousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblLokasiMousePressed
        
        int row = tblLokasi.rowAtPoint(evt.getPoint());

        if (row == -1) {
            tblLokasi.clearSelection(); 
            selectedId = -1;         
        }
    }//GEN-LAST:event_tblLokasiMousePressed


