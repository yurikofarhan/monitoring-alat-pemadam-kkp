    public void setData(InspeksiModel i) {

        this.idInspeksi = i.getIdInspeksi();
        this.idAlat = i.getIdAlat();

        // tanggal
        try {
            dateInspeksi.setDate(new java.util.Date(
                i.getTanggalInspeksi().getTime()
            ));
        } catch (Exception e) {
            dateInspeksi.setDate(null);
        }
        cmbKondisiAlat.setSelectedItem(EnumUtil.formatEnum(i.getKondisi()));
        cmbStatusAlat.setSelectedItem(EnumUtil.formatEnum(i.getStatus()));
        cmbStatusInspeksi.setSelectedItem(EnumUtil.formatEnum(i.getStatusInspeksi()));
        txtKeterangan.setText(i.getKeterangan());
    }
