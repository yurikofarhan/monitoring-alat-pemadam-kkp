    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        try {

            java.util.Date tanggal = dateInspeksi.getDate();
            String kondisi = cmbKondisiAlat.getSelectedItem().toString()
                    .toLowerCase()
                    .replace(" ", "_");
            String status = cmbStatusAlat.getSelectedItem().toString()
                    .toLowerCase()
                    .replace(" ", "_");
            String statusInspeksi = cmbStatusInspeksi.getSelectedItem().toString()
                    .toLowerCase()
                    .replace(" ", "_");
            String ket = txtKeterangan.getText();

            boolean sukses = controller.update(
                idInspeksi,
                idAlat,
                tanggal,
                kondisi,
                status,
                statusInspeksi,
                ket
            );
            
            if (sukses) {
                JOptionPane.showMessageDialog(this, "Berhasil update!");
                dispose();
            } else {
                JOptionPane.showMessageDialog(this, "Gagal update!");
            }
            
            

        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }//GEN-LAST:event_jButton2ActionPerformed

