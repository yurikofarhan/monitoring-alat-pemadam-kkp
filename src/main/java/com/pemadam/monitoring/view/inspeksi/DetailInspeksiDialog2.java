    private void loadKondisiAlat() {

        InspeksiDAO dao = new InspeksiDAO();
        DefaultComboBoxModel<String> model = new DefaultComboBoxModel<>();

        for (String s : dao.getEnumKondisiAlat()) {
            model.addElement(EnumUtil.formatEnum(s));
        }

        cmbKondisiAlat.setModel(model);
    }
    
