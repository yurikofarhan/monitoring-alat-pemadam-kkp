    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
        // TODO add your handling code here:
        if (selectedId == -1) {
            javax.swing.JOptionPane.showMessageDialog(parent, "Pilih data dulu!");
            return;
        }
        PenggunaController controller = new PenggunaController();
        PenggunaModel p = controller.getPenggunaById(selectedId);
        DetailPenggunaDialog dialog = new DetailPenggunaDialog(parent, true);

        dialog.setData(
            p.getIdPengguna(),
            p.getNamaPengguna(),
            p.getUsername(),
            p.getNoTelp(),
            p.getRole()
        );

        dialog.setLocationRelativeTo(this);
        dialog.setVisible(true);

        loadData(); 
    }//GEN-LAST:event_btnEditActionPerformed

    private void tblPenggunaMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblPenggunaMouseClicked
       
        int row = tblPengguna.getSelectedRow();

        if (row != -1) {
            selectedId = Integer.parseInt(tblPengguna.getValueAt(row, 0).toString());
        }
    }//GEN-LAST:event_tblPenggunaMouseClicked

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
       
         if (selectedId == -1) {
            javax.swing.JOptionPane.showMessageDialog(parent, "Pilih data dulu!");
            return;
        }

        int confirm = javax.swing.JOptionPane.showConfirmDialog(
            parent,
            "Yakin mau hapus data ini?",
            "Konfirmasi",
            javax.swing.JOptionPane.YES_NO_OPTION
        );

        if (confirm == javax.swing.JOptionPane.YES_OPTION) {

            PenggunaController controller = new PenggunaController();
            boolean sukses = controller.deletePengguna(selectedId);

            if (sukses) {
                javax.swing.JOptionPane.showMessageDialog(parent, "Data berhasil dihapus!");
                loadData();   
                selectedId = -1;
            } else {
                javax.swing.JOptionPane.showMessageDialog(parent, "Gagal hapus data!");
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void tblPenggunaMousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblPenggunaMousePressed
        
        int row = tblPengguna.rowAtPoint(evt.getPoint());

        if (row == -1) {
            tblPengguna.clearSelection(); 
            selectedId = -1;         
        }
    }//GEN-LAST:event_tblPenggunaMousePressed


