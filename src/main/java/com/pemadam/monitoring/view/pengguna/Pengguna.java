    private void loadData() {
        DefaultTableModel model = (DefaultTableModel) tblPengguna.getModel();
        model.setRowCount(0);

        PenggunaController controller = new PenggunaController();
        List<PenggunaModel> list = controller.getAllPengguna();

        for (PenggunaModel p : list) {
            model.addRow(new Object[]{
                p.getIdPengguna(),
                p.getNamaPengguna(),
                p.getUsername(),
                p.getNoTelp(),
                p.getRole()
            });
        }
    }
    
    
